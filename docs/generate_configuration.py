"""Write ``docs/configuration.md``, the configuration reference, from the
defaults file and the shipped configurations.

Every default is read from ``wdf/config/defaults.toml``: its value, and the
unit and meaning of its ``# [unit] meaning`` comment. The page has two parts:

- the keys of the shipped configurations (``configs/*.toml``): for each, its
  default (from every table of the defaults file that holds it, or
  "required" for a key the run must give, `wdf.config.Parameters.REQUIRED_KEYS`),
  its unit, its value in each shipped configuration and its meaning;
- the defaults file table by table: every key, its default, unit and meaning.

Run from the repository root::

    python docs/generate_configuration.py            # writes the page
    python docs/generate_configuration.py --check    # exit 1 if it is stale
"""
import argparse
import os
import re
import sys

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    import tomli as tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

OUTPUT = os.path.join(ROOT, "docs", "configuration.md")
DEFAULTS = os.path.join(ROOT, "wdf", "config", "defaults.toml")
#: The shipped configurations, in the column order of the page.
CONFIGS = ("online_default", "online_zerophase_default", "online_zerophase_track", "offline_default",
           "offline_c20")
TABLE = re.compile(r"^\s*\[([^\]]+)\]\s*(?:#.*)?$")
ASSIGNMENT = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=.*?#\s*(.*)$")
UNIT = re.compile(r"^\[([^\]]+)\]\s*(.*)$")
UNSET = "<unset>"


def read(path):
    with open(path) as fh:
        return fh.read()


def comments(path):
    """``{(table, key): comment}`` of the assignments of a TOML file; the
    table of a top-level key is None."""
    out, table = {}, None
    for line in read(path).splitlines():
        m = TABLE.match(line)
        if m:
            table = m.group(1).strip()
            continue
        m = ASSIGNMENT.match(line)
        if m:
            out[(table, m.group(1))] = m.group(2).strip()
    return out


def defaults_file():
    """``(tables, notes)``: ``{table: {key: value}}`` in file order and
    ``{(table, key): (unit, meaning)}``."""
    with open(DEFAULTS, "rb") as fh:
        data = tomllib.load(fh)
    tables = {}

    def walk(prefix, table):
        values = {k: v for k, v in table.items() if not isinstance(v, dict)}
        if prefix and values:
            tables[prefix] = values
        for key, value in table.items():
            if isinstance(value, dict):
                walk(f"{prefix}.{key}" if prefix else key, value)

    walk("", data)
    notes = {}
    for where, text in comments(DEFAULTS).items():
        m = UNIT.match(text)
        notes[where] = (m.group(1), m.group(2)) if m else ("", text)
    order = [t for t, _ in comments(DEFAULTS)]
    tables = dict(sorted(tables.items(), key=lambda kv: order.index(kv[0])
                         if kv[0] in order else len(order)))
    return tables, notes


def show(value):
    """A value as a TOML file writes it."""
    if value is None:
        return "--"
    if value == UNSET:
        return "unset"
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, str):
        return f'`"{value}"`'
    if isinstance(value, (list, tuple)):
        return "`[" + ", ".join(show(v).strip("`") for v in value) + "]`"
    if isinstance(value, float) and value.is_integer() and abs(value) < 1e15:
        return f"`{value:.1f}`"
    return f"`{value!r}`"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def generate():
    from wdf.config.Parameters import DETECTOR_TABLE, REQUIRED_KEYS

    tables, notes = defaults_file()
    paths = {name: os.path.join(ROOT, "configs", f"{name}.toml") for name in CONFIGS}
    values, per_detector, config_notes = {}, {}, {}
    for name, path in paths.items():
        with open(path, "rb") as fh:
            data = tomllib.load(fh)
        detectors = data.pop(DETECTOR_TABLE, {})
        values[name] = data
        per_detector[name] = {}
        for ifo, table in detectors.items():
            for key, value in table.items():
                per_detector[name].setdefault(key, {})[ifo] = value
        for (table, key), text in comments(path).items():
            if table is None:
                config_notes.setdefault(key, text)
    keys = []
    for name in CONFIGS:
        for key in list(values[name]) + list(per_detector[name]):
            if key not in keys:
                keys.append(key)

    holders = {}
    for table, entries in tables.items():
        for key in entries:
            holders.setdefault(key, []).append(table)

    lines = [
        "# Configuration reference",
        "",
        "<!-- Generated by docs/generate_configuration.py from wdf/config/defaults.toml and",
        "     configs/*.toml; do not edit by hand. -->",
        "",
        "A run is configured by a TOML file, loaded with",
        "`wdf.config.Parameters.load_config(path, ifo)`. Its top-level keys are the run's",
        "parameters; a `[detectors.<IFO>]` table overrides them for one detector. Every",
        "value the run uses is written to its `parametersUsed` file.",
        "",
        "Every default lives in one file shipped with the package,",
        "`wdf/config/defaults.toml`, read by `wdf.config.defaults.defaults(table)`. A key",
        "the run configuration does not set takes its default from the table of the",
        "stage that reads it; a library function's default arguments are read from the",
        "same file. \"unset\" is a default the code derives, as the meaning states;",
        "\"required\" a key the run must give.",
        "",
        "Units: samples are samples of the decimated stream; \"fraction of Nyquist\"",
        "is a fraction of the Nyquist frequency of that stream; \"-\" is dimensionless.",
        "",
        "The flows these configurations run, and the offline follow-up of a stretch",
        "with `configs/offline_c20.toml`, are described in",
        "[Online and offline](design/online-offline.md).",
        "",
        "## Keys of the shipped configurations",
        "",
        "Default is the value of every table of the defaults file holding the key",
        "(a key read by several stages has one default per stage); the meaning is the",
        "shipped configurations' comment. The five columns that follow are the shipped configurations, a value set per",
        "detector given as `H1/L1/V1`; -- is a key the file does not set.",
        "",
        "| Key | Default | Unit | online | online zero-phase | online zero-phase track | offline "
        "| offline C20 | Meaning |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for key in keys:
        where = holders.get(key, [])
        if where:
            shown = {t: show(tables[t][key]) for t in where}
            if len(set(shown.values())) == 1:
                default = next(iter(shown.values()))
            else:
                default = "<br>".join(f"{v} (`[{t}]`)" for t, v in shown.items())
            unit, meaning = notes.get((where[0], key), ("", ""))
            meaning = config_notes.get(key) or meaning
        else:
            default = "required" if key in REQUIRED_KEYS else "--"
            unit, meaning = "", config_notes.get(key, "")
        row = [f"`{key}`", default, cell(unit)]
        for name in CONFIGS:
            per = per_detector[name].get(key)
            if per:
                row.append("/".join(show(per.get(i)).strip("`") for i in ("H1", "L1", "V1")))
            else:
                row.append(show(values[name].get(key)))
        row.append(cell(meaning))
        lines.append("| " + " | ".join(row) + " |")

    lines += [
        "",
        "## The defaults file",
        "",
        "Every key of `wdf/config/defaults.toml`, by table. A CamelCase key is the",
        "default of the run-configuration key of the same name; a lower-case key is the",
        "default of a library argument or setting of the module the table is named after.",
    ]
    for table, entries in tables.items():
        lines += ["", f"### `[{table}]`", "", "| Key | Default | Unit | Meaning |", "|---|---|---|---|"]
        for key, value in entries.items():
            unit, meaning = notes.get((table, key), ("", ""))
            lines.append(f"| `{key}` | {show(value)} | {cell(unit)} | {cell(meaning)} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is stale")
    args = parser.parse_args()
    text = generate()
    if args.check:
        current = read(OUTPUT) if os.path.exists(OUTPUT) else ""
        if current != text:
            print(f"{OUTPUT} is stale: run python docs/generate_configuration.py")
            return 1
        return 0
    with open(OUTPUT, "w") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
